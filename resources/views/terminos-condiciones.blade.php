        </p>

        <h2>4. Planes y Pagos</h2>

        <h3>4.1 Planes de Suscripción</h3>
        <p>
            Ofrecemos tres planes de suscripción mensual: Plan Básico con funcionalidades esenciales para APR pequeñas, Plan Profesional con funcionalidades avanzadas y módulos adicionales, y Plan Enterprise con funcionalidades completas y soporte prioritario.
        </p>

        <h3>4.2 Facturación</h3>
        <p>
            La facturación se realiza mensualmente por adelantado. Los pagos se procesan automáticamente el día correspondiente de cada mes.
        </p>

        <h3>4.3 Cambios de Plan</h3>
        <p>
            En caso de mejora de plan (upgrade), se cobra la diferencia prorrateada del período restante. En caso de reducción de plan (downgrade), el cambio se aplica al final del período de facturación actual.
        </p>

        <h3>4.4 Cancelación</h3>
        <p>
            Puede cancelar su suscripción en cualquier momento. La cancelación será efectiva al final del período de facturación actual. No se realizan reembolsos por períodos parciales.
        </p>

        <h2>5. Uso Aceptable</h2>
        <p>
