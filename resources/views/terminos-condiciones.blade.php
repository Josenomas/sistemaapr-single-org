        <h3>7.1 Tiempo de Actividad</h3>
        <p>
            Nos esforzamos por mantener una disponibilidad del servicio del 99.9%, aunque no podemos garantizar un tiempo de actividad ininterrumpido debido a factores fuera de nuestro control, como mantenimientos de infraestructura, actualizaciones de seguridad o eventos de fuerza mayor.
        </p>

        <h3>7.2 Mantenimiento</h3>
        <p>
            Nos reservamos el derecho de realizar mantenimiento programado con previo aviso. Intentaremos realizar el mantenimiento en horarios de baja actividad para minimizar el impacto en las operaciones de su organización.
